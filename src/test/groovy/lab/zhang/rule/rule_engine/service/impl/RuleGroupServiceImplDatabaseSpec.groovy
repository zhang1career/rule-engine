                        .id(rule.getId())
                        .name(rule.getName())
                        .contentType(rule.getContentType())
                        .content(rule.getContent())
                        .description(rule.getDescription())
                        .ruleStatus(RuleStatusEnum.GRAY)
                        .build()
                ruleService.updateRule(ruleToUpdate.getId(), ruleToUpdate)
            }
        }

