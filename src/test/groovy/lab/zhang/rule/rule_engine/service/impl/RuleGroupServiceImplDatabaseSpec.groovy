            def groupId = getRuleGroupIdForRuleAndEvent(actualRuleId, eventId)
            assert groupId != null && groupId != 0L : "Rule should have a group ID for event ${eventId} after transitioning to ONLINE. RuleId: ${actualRuleId}"
            
