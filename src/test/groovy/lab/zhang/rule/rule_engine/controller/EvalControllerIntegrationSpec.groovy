    def "test eval interface - execution trace details"() {
        given: "prepare eval request"
        def evalQO = new EvalQO()
        evalQO.userId = 1000L
        evalQO.eventId = EVENT_ID_2
        evalQO.traceId = 9999L
        evalQO.arguments = [
                "amount": new TypedValue(150.0, ValueTypeEnum.DECIMAL)
        ]

        when: "call eval interface"
        def response = evalController.eval(evalQO)

        then: "execution trace should contain detailed information"
        response.statusCode == HttpStatus.OK
        def trace = response.body.trace
        trace != null
        trace.steps != null

        and: "each step should have proper structure"
        trace.steps.eachWithIndex { step, index ->
            // Execution order is implied by the position in the list (index + 1)
            assert step.itemType != null
            assert step.itemId != null
            // All steps in trace are executed rules
            if (step.itemType == ExecutionItemTypeEnum.RULE) {
                // itemId should be rule ID
            } else if (step.itemType == ExecutionItemTypeEnum.RULE_GROUP) {
                // itemId should be rule group ID
                // If abTestedRuleId is not null, it means a rule was selected from the group
            }
            // Each executed step should have either a result or an error message
            assert step.result != null || step.errmsg != null
        }

        and: "should print execution trace for inspection"
        println "\nExecution Trace:"
        trace.steps.eachWithIndex { step, index ->
            def stepInfo = "Step ${index + 1}: ${step.itemType}"
            if (step.itemType == ExecutionItemTypeEnum.RULE) {
                stepInfo += " (Item ID: ${step.itemId})"
            } else {
                stepInfo += " (Item ID: ${step.itemId}, Selected Rule ID: ${step.abTestedRuleId})"
            }
            if (step.result != null) {
                stepInfo += ", Result: ${step.result}"
            }
            if (step.errmsg != null) {
                stepInfo += ", Error: ${step.errmsg}"
            }
            // Last step is the last executed rule
            if (index == trace.steps.size() - 1) {
                stepInfo += " [LAST EXECUTED]"
            }
            println "  ${stepInfo}"
        }
    }

    // Helper methods
    private void setupTestData() {
        // Create 3 events
        createEvent(EVENT_ID_1, "Event 1")
        createEvent(EVENT_ID_2, "Event 2")
        createEvent(EVENT_ID_3, "Event 3")

        // Create 6 rules with different statuses
        // Rule 1: OFFLINE
        ruleId1 = createRule("Rule 1 - OFFLINE", ContentTypeEnum.SCRIPT, RuleStatusEnum.OFFLINE, "return amount > 50")

        // Rule 2: TEST
        ruleId2 = createRule("Rule 2 - TEST", ContentTypeEnum.SCRIPT, RuleStatusEnum.TEST, "return amount > 100")
        transitionRuleToStatus(ruleId2, RuleStatusEnum.TEST)

        // Rule 3: GRAY
        ruleId3 = createRule("Rule 3 - GRAY", ContentTypeEnum.SCRIPT, RuleStatusEnum.GRAY, "return amount > 150")
        transitionRuleToStatus(ruleId3, RuleStatusEnum.TEST)
        transitionRuleToStatus(ruleId3, RuleStatusEnum.GRAY)

        // Rule 4: AB_TEST (in group)
        ruleId4 = createRule("Rule 4 - AB_TEST", ContentTypeEnum.SCRIPT, RuleStatusEnum.AB_TEST, "return amount > 200")
        transitionRuleToStatus(ruleId4, RuleStatusEnum.TEST)
        transitionRuleToStatus(ruleId4, RuleStatusEnum.GRAY)
        transitionRuleToStatus(ruleId4, RuleStatusEnum.AB_TEST)

        // Rule 5: AB_TEST (in group)
        ruleId5 = createRule("Rule 5 - AB_TEST", ContentTypeEnum.SCRIPT, RuleStatusEnum.AB_TEST, "return amount > 250")
        transitionRuleToStatus(ruleId5, RuleStatusEnum.TEST)
        transitionRuleToStatus(ruleId5, RuleStatusEnum.GRAY)
        transitionRuleToStatus(ruleId5, RuleStatusEnum.AB_TEST)

        // Rule 6: FULL
        ruleId6 = createRule("Rule 6 - FULL", ContentTypeEnum.SCRIPT, RuleStatusEnum.FULL, "return amount > 300")
        transitionRuleToStatus(ruleId6, RuleStatusEnum.TEST)
        transitionRuleToStatus(ruleId6, RuleStatusEnum.GRAY)
        transitionRuleToStatus(ruleId6, RuleStatusEnum.AB_TEST)
        transitionRuleToStatus(ruleId6, RuleStatusEnum.FULL)

        // Create rule group with rule 4 and rule 5
        // Note: When rule4 transitions to AB_TEST, a group is automatically created
        def rule4 = ruleService.getRuleById(ruleId4)
        def groupId = rule4.getRuleGroupId()
        assert groupId != null : "Rule 4 should have a group ID after transitioning to AB_TEST"

        // Add rule 5 to the same group
        def rule5 = ruleService.getRuleById(ruleId5)
        // If rule5 already has a group (created when transitioning to AB_TEST), we need to handle it
        if (rule5.getRuleGroupId() != null && rule5.getRuleGroupId() != groupId) {
            // Remove rule5 from its current group and add to rule4's group
            // First, set rule5 to OFFLINE to remove it from its group
            def rule5Offline = Rule.builder()
                    .id(rule5.getId())
                    .name(rule5.getName())
                    .contentType(rule5.getContentType())
                    .content(rule5.getContent())
                    .description(rule5.getDescription())
                    .ruleStatus(RuleStatusEnum.OFFLINE)
                    .ruleGroupId(null)
                    .build()
            ruleService.updateRule(ruleId5, rule5Offline)
            // Then transition back to AB_TEST with the target groupId (OFFLINE -> TEST -> GRAY -> AB_TEST)
            transitionRuleToStatus(ruleId5, RuleStatusEnum.TEST)
            transitionRuleToStatus(ruleId5, RuleStatusEnum.GRAY)
            // Update rule5 to AB_TEST with target groupId
            rule5 = ruleService.getRuleById(ruleId5)
            def rule5ABTest = Rule.builder()
                    .id(rule5.getId())
                    .name(rule5.getName())
                    .contentType(rule5.getContentType())
                    .content(rule5.getContent())
                    .description(rule5.getDescription())
                    .ruleStatus(RuleStatusEnum.AB_TEST)
                    .ruleGroupId(groupId)
                    .build()
            ruleService.updateRule(ruleId5, rule5ABTest)
        } else if (rule5.getRuleGroupId() == null) {
            // Add rule 5 to the group
            ruleGroupService.addRuleToGroup(rule5, groupId)
        }

        // Update rule group with ratios: rule4=10, rule5=50
        // Note: Both rules must already be in AB_TEST status and in the group
        def rules = [(ruleId4): 10, (ruleId5): 50]
        ruleGroupService.updateRuleGroupWithRules(groupId, rules)

        // Create event-rule associations
        // Event 16000001: with some rules (rule2, rule3)
        createRuleEventRelation(EVENT_ID_1, ruleId2, 1)
        createRuleEventRelation(EVENT_ID_1, ruleId3, 2)

        // Event 16000002: with all rules and rule group
        createRuleEventRelation(EVENT_ID_2, ruleId1, 1)
        createRuleEventRelation(EVENT_ID_2, ruleId2, 2)
        createRuleEventRelation(EVENT_ID_2, ruleId3, 3)
        createRuleEventRelation(EVENT_ID_2, ruleId6, 4)
        createGroupEventRelation(EVENT_ID_2, groupId, 5)

        // Event 16000003: no rules (already handled in test)
    }

    private void createEvent(Long eventId, String name) {
        eventService.createEvent(eventId, name, "Test event: ${name}")
    }

    private Long createRule(String name, ContentTypeEnum type, RuleStatusEnum status, String content) {
        def rule = Rule.builder()
                .id(null)  // Let database auto-generate ID
                .name(name)
                .contentType(type)
                .ruleStatus(status)
                .content(content)
                .description("Test rule: ${name}")
                .build()
        ruleService.createRule(rule)
        return rule.getId()
    }

    private void transitionRuleToStatus(Long ruleId, RuleStatusEnum targetStatus) {
        def rule = ruleService.getRuleById(ruleId)
        if (rule == null) {
            throw new IllegalArgumentException("Rule not found: ${ruleId}")
        }
        def ruleToUpdate = Rule.builder()
                .id(rule.getId())
                .name(rule.getName())
                .contentType(rule.getContentType())
                .content(rule.getContent())
                .description(rule.getDescription())
                .ruleStatus(targetStatus)
                .ruleGroupId(rule.getRuleGroupId())
                .build()
        ruleService.updateRule(ruleId, ruleToUpdate)
    }

    private void createRuleEventRelation(Long eventId, Long ruleId, Integer order) {
        def relation = new ExecutionEventRelationEntity()
        relation.setEventId(eventId)
        relation.setItemType(ExecutionItemTypeEnum.RULE.getId())
        relation.setItemId(ruleId)
        relation.setExecutionOrder(order)
        long currentTime = (long) (System.currentTimeMillis() / 1000)
        relation.setCt((int) currentTime)
        relation.setUt((int) currentTime)
        executionEventRelationMapper.insert(relation)
    }

    private void createGroupEventRelation(Long eventId, Long groupId, Integer order) {
        def relation = new ExecutionEventRelationEntity()
        relation.setEventId(eventId)
        relation.setItemType(ExecutionItemTypeEnum.RULE_GROUP.getId())
        relation.setItemId(groupId)
        relation.setExecutionOrder(order)
        long currentTime = (long) (System.currentTimeMillis() / 1000)
        relation.setCt((int) currentTime)
        relation.setUt((int) currentTime)
        executionEventRelationMapper.insert(relation)
    }
