    // Test data IDs
    private static final Long EVENT_ID_1 = 16000001L
    private static final Long EVENT_ID_2 = 16000002L
    private static final Long EVENT_ID_3 = 16000003L
    private static final Long RULE_GROUP_ID = 16002001L

    // Rule IDs (will be auto-generated by database)
    private Long ruleId1  // OFFLINE
    private Long ruleId2  // TEST
    private Long ruleId3  // GRAY
    private Long ruleId4  // AB_TEST (in group)
    private Long ruleId5  // AB_TEST (in group)
    private Long ruleId6  // FULL

    def setup() {
        // Clean up test data before each test
        executionEventRelationMapper.delete(null)
        ruleGroupRuleRelationMapper.delete(null)
        ruleGroupMapper.delete(null)
        ruleMapper.delete(null)
        eventMapper.delete(null)

        // Setup test data
        setupTestData()
    }

    def "test eval interface - integration test with execution trace"() {
        given: "prepare eval request"
        def evalQO = new EvalQO()
        evalQO.userId = 1000L
        evalQO.eventId = EVENT_ID_2
        evalQO.traceId = 9999L
        evalQO.arguments = [
                "amount": new TypedValue(150.0, ValueTypeEnum.DECIMAL)
        ]

        when: "call eval interface"
        def response = evalController.eval(evalQO)

        then: "should return success response with execution trace"
        response.statusCode == HttpStatus.OK
        response.body != null
        response.body.success == true
        response.body.result != null
        response.body.trace != null
        response.body.trace.steps != null
        response.body.trace.steps.size() > 0

        and: "execution trace should contain execution steps"
        def steps = response.body.trace.steps
        steps.each { step ->
            assert step.itemType != null
            assert step.itemId != null
            // All steps in trace are executed rules
            assert step.result != null || step.errmsg != null
        }

        and: "should have executed rules for event 16000002"
        steps.size() > 0
    }

    def "test eval interface - multiple requests to analyze rule group selection distribution"() {
        given: "prepare multiple eval requests with random amount values"
        def requestCount = 1000
        def ruleSelectionCounts = [:]
        def totalExecutions = 0

        when: "call eval interface multiple times"
        requestCount.times { index ->
            def amount = Math.random() * 500  // Random amount between 0 and 500
            def evalQO = new EvalQO()
            evalQO.userId = 1000L + index  // Different userId for each request
            evalQO.eventId = EVENT_ID_2
            evalQO.traceId = 9999L + index
            evalQO.arguments = [
                    "amount": new TypedValue(amount, ValueTypeEnum.DECIMAL)
            ]

            def response = evalController.eval(evalQO)
            assert response.statusCode == HttpStatus.OK
            assert response.body.success == true

            // Analyze execution trace
            def trace = response.body.trace
            if (trace != null && trace.steps != null) {
                trace.steps.each { step ->
                    if (step.itemType == ExecutionItemTypeEnum.RULE_GROUP) {
                        // All steps in trace are executed rules
                        totalExecutions++
                        def selectedRuleId = step.abTestedRuleId
                        if (selectedRuleId != null) {
                            ruleSelectionCounts[selectedRuleId] = (ruleSelectionCounts[selectedRuleId] ?: 0) + 1
                        }
                    }
                }
            }
        }

        then: "should have execution traces for all requests"
        totalExecutions > 0

        and: "rule group selection should follow probability distribution"
        // Rule group has 2 rules with ratios 10 and 50 (total 60, leaving 40% for no selection)
        // Expected distribution: rule4 ~10%, rule5 ~50%, no selection ~40%
        if (totalExecutions > 0) {
            def rule4Count = ruleSelectionCounts[ruleId4] ?: 0
            def rule5Count = ruleSelectionCounts[ruleId5] ?: 0
            def rule4Percentage = (rule4Count / totalExecutions) * 100
            def rule5Percentage = (rule5Count / totalExecutions) * 100
            def noSelectionPercentage = ((totalExecutions - rule4Count - rule5Count) / totalExecutions) * 100

            println "Rule Group Selection Distribution (${totalExecutions} executions):"
            println "  Rule ${ruleId4} (ratio 10): ${rule4Count} times (${String.format("%.2f", rule4Percentage)}%)"
            println "  Rule ${ruleId5} (ratio 50): ${rule5Count} times (${String.format("%.2f", rule5Percentage)}%)"
            println "  No selection: ${totalExecutions - rule4Count - rule5Count} times (${String.format("%.2f", noSelectionPercentage)}%)"

            // Allow some variance (within 5% of expected)
            rule4Percentage >= 5 && rule4Percentage <= 15  // Expected ~10%
            rule5Percentage >= 45 && rule5Percentage <= 55  // Expected ~50%
            noSelectionPercentage >= 35 && noSelectionPercentage <= 45  // Expected ~40%
        } else {
            // If no executions, it might be because environment doesn't allow AB_TEST rules
            println "Warning: No rule group executions found. This might be due to environment configuration."
            // In GRAY environment, AB_TEST rules should execute, so this should not happen
            assert false : "Expected rule group executions but found none. Check environment configuration."
        }
    }

